def write_master() -> None:
    with (HERE / "calendar-x-week1.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, quoting=csv.QUOTE_ALL)
        w.writerow(["date", "time_cet", "day", "language", "format", "text", "link", "image", "notes"])
        for p in POSTS:
            w.writerow([p.date, p.time, p.day, p.language, p.fmt, p.text, p.link, p.image, p.notes])


def write_buffer() -> None:
    # Buffer's bulk upload supports text + one image. Polls and threads are
    # excluded and should be scheduled manually in the X composer.
    with (HERE / "buffer-x-week1.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, quoting=csv.QUOTE_ALL)
        w.writerow(["Text", "Image URL", "Tags", "Posting Time"])
        for p in POSTS:
            if p.fmt in {"poll", "thread"}:
                continue
            w.writerow([p.text, p.image, "Aegis OS", f"{p.date} {p.time}"])


def write_typefully() -> None:
    # Typefully's community CLI/SDK bulk import accepts this shape:
    # content,scheduled_date,threadify
    with (HERE / "typefully-x-week1.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, quoting=csv.QUOTE_ALL)
        w.writerow(["content", "scheduled_date", "threadify"])
        for p in POSTS:
            content = "\n\n".join(p.thread) if p.thread else p.text
            w.writerow([content, f"{p.date} {p.time}:00", "true" if p.thread else "false"])


if __name__ == "__main__":
    write_master()
    write_buffer()
    write_typefully()
    print(f"wrote {len(POSTS)} posts to {HERE}")
    print("buffer rows:", sum(1 for p in POSTS if p.fmt not in {"poll", "thread"}))
    print("manual rows: poll + thread (2)")
