  await page.click('#genForm button.primary')
  await page.waitForSelector('.rs-cohort-ds', { timeout: 15000 }).catch(() => {})
  const dsText = await page.locator('.rs-cohort-ds').first().innerText().catch(() => '')
  ok('生成研究数据集（宽表 v1，最新）', dsText.includes('宽表 v1') && dsText.includes('最新'), dsText)
  const sets = (await api(`/api/studies/${study.id}/cohort`)).datasets
  const prev = sets[0] ? await api(`/api/datasets/${sets[0].dataset_id}/preview`) : null
  ok('研究数据集里只有研究编号、没有代号', !!prev && JSON.stringify(prev).includes('S001') && !JSON.stringify(prev).includes(hi.code))
  await page.click(`.rs-subjects [data-patient="${hi.id}"]`)
  await page.waitForSelector('.pt-study', { timeout: 5000 }).catch(() => {})
