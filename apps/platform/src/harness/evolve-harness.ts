import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import type { Store } from '../store/db.ts'
import type { Complete } from '../memory/evolve.ts'

export interface EvolvedHarnessResult {
  summary: string
  recurrentPatterns: Array<{ code: string; count: number }>
  rules: string[]
  overlayYaml: string
}

const BASE_PROFILE_PATH = fileURLToPath(new URL('./profile/heurion.cordis.yml', import.meta.url))

const SYSTEM_HARNESS_EVOLVER = `你正在执行 Heurion 2.0 的元级执行策略自演进。
你的任务是根据平台近期的 Agent 执行失败信号（如写前守卫拦截 conflict_user_edited、引用违规 citation_not_registered、用户撤销回合 user_reverted_turn 等）和已有策略，对 Agent 的底层执行指令进行全局优化与提纯。

输入为 JSON：
- signals: 近期未被消费的执行异常与拦截记录
- active_rules: 现有已沉淀的局部策略规则

请分析错误根因，产出针对性的系统级执行规范（附加到 Agent 的 personaSuffix 指令中）。
要求：
1. 提炼出的规则必须高度可操作、防止同类错误再次发生。
2. 保持中文表述清晰专业，规则总数控制在 2-5 条，单条不超过 100 字。
3. 严格输出 JSON 格式：
{
  "summary": "本次策略演进的总结与优化要点说明",
  "rules": [
    "执行规范 1...",
    "执行规范 2..."
  ]
}`

export class HarnessEvolutionService {
  constructor(
    private readonly store: Store,
    private readonly complete: Complete | null,
  ) {}

  available(): boolean {
    return this.complete !== null
  }

  /** 获取当前已生效的动态配置补丁 YAML（若无则返回 null）。 */
  currentOverlay(): string | null {
    return this.store.getAppSetting('evolved_harness_patch')
  }

  /** 获取最近一次元策略演进的元数据。 */
  currentMeta(): { summary: string; rules: string[]; at: string } | null {
    const raw = this.store.getAppSetting('evolved_harness_meta')
    if (!raw) return null
    try {
      return JSON.parse(raw) as { summary: string; rules: string[]; at: string }
    } catch {
      return null
    }
  }

  /**
   * 触发一次全局执行策略自演进：
   * 聚合执行信号，分析失败模式，调用元模型提炼全局配置补丁并固化到平台设置。
   */
  async evolve(opts: { force?: boolean } = {}): Promise<EvolvedHarnessResult | { skipped: 'insufficient_signals' }> {
    if (!this.complete) throw new Error('未配置大模型，无法运行策略自演进')

    const signals = this.store.openExecutionSignals('system', 100)
    // 同时也拉取所有用户的待处理信号进行统计
    const patternCounts = new Map<string, number>()
    for (const s of signals) {
      patternCounts.set(s.code, (patternCounts.get(s.code) ?? 0) + 1)
    }

    if (!opts.force && signals.length < 3) {
      return { skipped: 'insufficient_signals' }
    }

    const activeRules = this.store.listHarnessRules('system', ['active'])
    const payload = {
      signals: signals.slice(0, 50).map(s => ({ kind: s.kind, code: s.code, detail: s.detail })),
      active_rules: activeRules.map(r => ({ category: r.category, trigger: r.trigger_pattern, rule: r.rule })),
    }

    const raw = await this.complete(SYSTEM_HARNESS_EVOLVER, JSON.stringify(payload))
    let parsed: { summary?: string; rules?: string[] }
    try {
      const match = /\{[\s\S]*\}/.exec(raw.replace(/```(?:json)?/g, ''))
      if (!match) throw new Error('模型未返回有效 JSON')
      parsed = JSON.parse(match[0]) as { summary?: string; rules?: string[] }
    } catch (err) {
      throw new Error(`策略演进解析模型回复失败: ${(err as Error).message}`)
    }

    const summary = parsed.summary ?? '系统自动沉淀执行策略'
    const rules = Array.isArray(parsed.rules) ? parsed.rules : []

    // 组装成 dsh profile patch YAML 格式
    const formattedRules = rules.map(r => `      - ${r}`).join('\n')
    const overlayYaml = `# Auto-generated by Heurion Self-Evolution Engine\n` +
      `- id: system-prompt\n` +
      `  config:\n` +
      `    personaSuffix: >-\n` +
      `      [Evolved Self-Improvement Execution Directives]:\n` +
      `${formattedRules}\n`

    this.store.setAppSetting('evolved_harness_patch', overlayYaml)
    this.store.setAppSetting('evolved_harness_meta', JSON.stringify({
      summary,
      rules,
      at: new Date().toISOString(),
    }))

    // 消费本次已分析的信号
    this.store.consumeExecutionSignals(signals.map(s => s.id))

    return {
      summary,
      recurrentPatterns: [...patternCounts.entries()].map(([code, count]) => ({ code, count })),
      rules,
      overlayYaml,
    }
  }

  /** 清除演进补丁，回退到基础 heurion.cordis.yml。 */
  reset(): void {
    this.store.setAppSetting('evolved_harness_patch', '')
    this.store.setAppSetting('evolved_harness_meta', '')
  }
}
